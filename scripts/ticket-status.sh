#!/usr/bin/env bash
# Prints every ticket's status, owner and assignee from docs/tickets, with a done count.
# `--markdown` prints the same table as Markdown, for docs/tickets/README.md:
#   scripts/ticket-status.sh --markdown > docs/tickets/README.md
set -euo pipefail

cd "$(dirname "$0")/../docs/tickets"

field() {
  sed -n "s/^\*\*$1:\*\* *//p" "$2" | head -n 1
}

markdown=false
[ "${1:-}" = "--markdown" ] && markdown=true

total=0
done_count=0
rows=""
for ticket in [0-9]*.md; do
  name="${ticket%.md}"
  # A status can carry a note after the keyword ("in-progress (waiting on Pis)").
  status="$(field Status "$ticket")"
  status="${status%% *}"
  owner="$(field Owner "$ticket")"
  # Older tickets have no Assignee line; the first word is the handle, the rest a note.
  assignee="$(field Assignee "$ticket")"
  assignee="${assignee%% *}"
  assignee="${assignee:--}"
  total=$((total + 1))
  [ "$status" = "done" ] && done_count=$((done_count + 1))
  if $markdown; then
    rows+="| [$name]($ticket) | $status | $owner | $assignee |"$'\n'
  else
    rows+="$(printf '%-52s %-16s %-16s %s' "$name" "$status" "$owner" "$assignee")"$'\n'
  fi
done

if $markdown; then
  printf '# Tickets\n\n**%d of %d done.** Generated by `scripts/ticket-status.sh --markdown`; do not edit by hand.\n\n' "$done_count" "$total"
  printf '| Ticket | Status | Owner | Assignee |\n|---|---|---|---|\n%s' "$rows"
else
  printf '%s\n%d of %d done\n' "$rows" "$done_count" "$total"
fi
